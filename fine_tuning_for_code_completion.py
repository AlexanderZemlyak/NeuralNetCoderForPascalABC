def load_and_split_dataset(tokenizer, config: TrainingConfig):
    with open(config.json_path, "r", encoding="utf-8") as f:
        raw_samples = json.load(f)

    # 1. Сначала перемешиваем и делим файлы на уровне КОРНЯ, чтобы избежать утечки данных (Data Leakage)
    random.seed(42)
    random.shuffle(raw_samples)

    split_idx = int(len(raw_samples) * config.train_split_ratio)
    train_files = raw_samples[:split_idx]
    val_files = raw_samples[split_idx:]

    builder = PascalFimDatasetBuilder(tokenizer, config)

    # 2. Нарезаем тренировочную и валидационную выборки по стратегиям
    train_texts = []
    for code in train_files:
        train_texts.extend(builder.process_sample(code))

    val_texts = []
    for code in val_files:
        val_texts.extend(builder.process_sample(code))

    print(f"Исходных программ: {len(raw_samples)}")
    print(f"Получено FIM-сэмплов для Обучения (Train): {len(train_texts)}")
    print(f"Получено FIM-сэмплов для Валидации (Val): {len(val_texts)}")

    train_dataset = Dataset.from_dict({"text": train_texts})
    val_dataset = Dataset.from_dict({"text": val_texts})

    return train_dataset, val_dataset

