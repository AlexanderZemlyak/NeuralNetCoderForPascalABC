def start_fine_tuning():
  # 1. Загрузка токенизатора
  tokenizer = AutoTokenizer.from_pretrained(config.model_name, trust_remote_code=True)
  tokenizer.pad_token = tokenizer.eos_token
  # 2. Подготовка датасета
  train_data, val_data = load_and_split_dataset(tokenizer, config)
  # 3. Квантование 4-бит (Для экономии памяти в Colab)
  bnb_config = BitsAndBytesConfig(
    load_in_4bit=True,
    bnb_4bit_quant_type="nf4",
    bnb_4bit_compute_dtype=torch.float16,
    bnb_4bit_use_double_quant=True
  )
  # 4. Загрузка модели Qwen Coder
  # print("Загрузка базовой модели в 4-бит...")
  model = AutoModelForCausalLM.from_pretrained(
    config.model_name,
    torch_dtype=torch.float32,
    # quantization_config=bnb_config,
    device_map="auto",
    trust_remote_code=True
  )
  # 5. Настройка LoRA (Компактный конфиг БЕЗ embed_tokens, как в выводах)
  peft_config = LoraConfig(
    task_type=TaskType.CAUSAL_LM,
    r=config.lora_r,
    lora_alpha=config.lora_alpha,
    lora_dropout=config.lora_dropout,
    target_modules=[
      "q_proj", "v_proj", "k_proj", "o_proj",
      "gate_proj", "up_proj", "down_proj"
    ] # Эмбеддинги заморожены, экономим память
  )

  total_train_samples = len(train_data)

  steps_per_epoch = total_train_samples // (config.batch_size * config.gradient_accumulation_steps)

  eval_per_epoch_count = 10

  eval_every_steps = steps_per_epoch // eval_per_epoch_count

  print('Валидация каждые', eval_every_steps, 'шагов')

  # 6. Настройка аргументов обучения HF
  sft_config = SFTConfig(
      output_dir=config.output_dir,
      per_device_train_batch_size=config.batch_size,
      per_device_eval_batch_size=config.batch_size,
      gradient_accumulation_steps=config.gradient_accumulation_steps,
      eval_strategy="steps",            # Рассчитываем Loss каждую эпоху
      eval_steps=eval_every_steps,
      logging_strategy="steps",
      logging_steps=1,
      learning_rate=config.learning_rate,
      num_train_epochs=config.epochs,
      bf16=False,
      fp16=False,
      save_strategy="steps",
      save_steps=eval_every_steps,
      report_to="none",
      disable_tqdm=True,
      dataset_text_field="text",
      max_length=config.max_seq_length,
      # lr_scheduler_type="cosine", # Плавное затухание
      # warmup_ratio=0.03,          # Мягкий старт
  )

  # 7. Инициализация SFTTrainer строго по его актуальной сигнатуре
  eval_callback = CodeCompletionEvalCallback(val_data, tokenizer, num_samples=40)
  speed_callback = SpeedLoggingCallback()

  trainer = SFTTrainer(
      model=model,
      args=sft_config,                  # Передаем SFTConfig сюда
      train_dataset=train_data,
      eval_dataset=val_data,
      peft_config=peft_config,
      processing_class=tokenizer,       # Токенизатор теперь передается в этот параметр
      callbacks=[eval_callback, speed_callback]
  )

  # 8. Запуск дообучения!
  print("Старт обучения...")
  trainer.train()

  # 9. Сохранение весов адаптера
  print(f"Обучение завершено. Сохраняю LoRA-адаптер в {config.output_dir}")
  trainer.model.save_pretrained(config.output_dir)

start_fine_tuning()

