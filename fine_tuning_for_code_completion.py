from transformers import TrainerCallback, TrainerControl, TrainingArguments, TrainerState

class SpeedLoggingCallback(TrainerCallback):
    """Callback для принудительного вывода скорости обучения (it/s) каждые N шагов."""
    def __init__(self):
        self.last_time = time.time()
        self.last_step = 0

    def on_log(self, args: TrainingArguments, state: TrainerState, control: TrainerControl, **kwargs):
        # Проверяем, что в логах есть метрики обучения (а не валидации)
        if state.log_history and "loss" in state.log_history[-1]:
            current_time = time.time()
            current_step = state.global_step

            # Считаем разницу во времени и шагах с момента прошлого логирования
            step_diff = current_step - self.last_step
            time_diff = current_time - self.last_time

            if time_diff > 0 and step_diff > 0:
                its = step_diff / time_diff  # итераций (шагов) в секунду
                # Сколько примеров кода обработано в секунду
                examples_per_sec = (step_diff * args.per_device_train_batch_size * args.gradient_accumulation_steps) / time_diff

                # Печатаем скорость прямо в консоль
                print(f"[*] Шаг {current_step}: Скорость = {its:.2f} it/s ({examples_per_sec:.2f} samples/s)")

            # Обновляем таймеры для следующего шага
            self.last_time = current_time
            self.last_step = current_step

