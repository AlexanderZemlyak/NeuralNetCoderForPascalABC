@dataclass
class TrainingConfig:
    # Пути и модель
    model_name: str = "Qwen/Qwen2.5-Coder-1.5B"
    json_path: str = "train_data_unified_for_completion.json"
    output_dir: str = "./qwen_lora_code_completion"

