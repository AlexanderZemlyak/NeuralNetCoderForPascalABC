# 3. ГИБРИДНЫЙ СКРИПТ НАРЕЗКИ СЭМПЛОВ В FIM-ШАБЛОН
# =====================================================================
class PascalFimDatasetBuilder:
    def __init__(self, tokenizer, config: TrainingConfig):
        self.tokenizer = tokenizer
        self.cfg = config

        # Токены FIM, зашитые в Qwen-Coder
        self.PREFIX_TOK = "<|fim_prefix|>"
        self.SUFFIX_TOK = "<|fim_suffix|>"
        self.MIDDLE_TOK = "<|fim_middle|>"
        self.EOS_TOK = tokenizer.eos_token or "<|endoftext|>"

    def clean_code(self, code: str) -> str:
      """Мягкая унификация кода.
      Безопасно удаляет комментарии, не трогая текст внутри строк '...'
      """
      # Паттерн находит:
      # 1. Сначала строковые литералы: 'любой текст' (включая экранированные кавычки '')
      # 2. Однострочные комментарии: //...
      # 3. Многострочные комментарии: {...} или (*...*)
      pattern = r"('[^']*')|(//.*?$)|(\{.*?\})|(\(\*.*?\*\))"

      def replacer(match):
          # Если сработала первая группа (match.group(1)), значит мы нашли СТРОКУ.
          # Мы возвращаем её обратно без изменений.
          if match.group(1) is not None:
              return match.group(1)
          # Во всех остальных случаях мы нашли комментарий — заменяем его на пустоту.
          return ""

      # Применяем замену ко всему тексту с флагами MULTILINE (для //) и DOTALL (для { })
      cleaned_code = re.sub(pattern, replacer, code, flags=re.MULTILINE | re.DOTALL)

      # Нормализуем пустые строки
      lines = [line.rstrip() for line in cleaned_code.splitlines() if line.strip()]
      return "\n".join(lines)


    def create_fim_structure(self, prefix: str, suffix: str, middle: str) -> str:
        """Собирает финальную строчку в официальном FIM-формате Qwen."""
        return f"{self.PREFIX_TOK}{prefix}{self.SUFFIX_TOK}{suffix}{self.MIDDLE_TOK}{middle}{self.EOS_TOK}"

    def process_sample(self, raw_code: str) -> List[str]:
        """Нарезает один файл Pascal на несколько FIM примеров по стратегиям."""
        code = self.clean_code(raw_code)
        if len(code) < 20:
            return []

        # -----------------------------------------------------------------
        # 🛡️ ШАГ 1: НАХОДИМ ФИЗИЧЕСКИЕ ИНДЕКСЫ ВСЕХ СТРОК '...' В КОДЕ
        # -----------------------------------------------------------------
        # Сохраняем диапазоны (tuple: start_char_idx, end_char_idx) строковых литералов
        string_ranges = [(m.start(), m.end()) for m in re.finditer(r"'[^']*'", code)]

        def is_inside_string(char_idx: int) -> bool:
            """Проверяет, попадает ли индекс символа внутрь какой-либо строки '...'"""
            for start, end in string_ranges:
                # Если индекс строго между открывающей и закрывающей кавычкой — это запретная зона
                if start < char_idx < end:
                    return True
            return False

        # -----------------------------------------------------------------
        # 📐 ШАГ 2: СБОР МАРКЕРОВ С ФИЛЬТРАЦИЕЙ ЗАПРЕТНЫХ ЗОН
        # -----------------------------------------------------------------

        # Группа А: Синтаксические маркеры
        raw_syntax = [m.end() for m in re.finditer(r'\b(?:begin|var|if|then|do|else|for|foreach|while|new)\b|:=|\.|\b[a-zA-Z_][a-zA-Z0-9_]*\(', code, flags=re.IGNORECASE)]
        syntax_markers = [pos for pos in raw_syntax if not is_inside_string(pos)]

        # Группа Б: Token Healing
        words = [m for m in re.finditer(r'\b[a-zA-Z_][a-zA-Z0-9_]{3,}\b', code)]
        mid_word_borders = []
        for w in words:
            # Если хотя бы начало слова не в строке — проверяем его внутренности
            if not is_inside_string(w.start()):
                # Ставим каретку случайно внутрь слова, гарантируя безопасность
                mid_word_borders.append(random.randint(w.start() + 1, w.end() - 1))

        # Группа В: Границы токенизатора Qwen
        qwen_enc = self.tokenizer.encode(code, add_special_tokens=False)
        qwen_borders = []
        curr_idx = 0
        for t_id in qwen_enc:
            curr_idx += len(self.tokenizer.decode([t_id]))
            # Добавляем границу токена Qwen ТОЛЬКО если она не режет чью-то текстовую строку изнутри
            if not is_inside_string(curr_idx):
                qwen_borders.append(curr_idx)

        # Группа Г: Лексический анализатор Паскаля
        raw_lexical = get_pascal_lexical_borders(code)
        lexical_borders = [pos for pos in raw_lexical if not is_inside_string(pos)]

        # Определяем, будет ли в этом сэмпле пустой суффикс (симуляция конца файла)
        is_empty_suffix = random.random() < self.cfg.empty_suffix_ratio

        # Распределяем, сколько вариантов нарезки сделать на этот файл
        # Пока без lexical
        strategies = ['syntax', 'healing', 'qwen']
        weights = [
            self.cfg.group_syntax_ratio,
            self.cfg.group_token_healing_ratio,
            self.cfg.group_qwen_border_ratio
        ]

        # Сделаем, например, 4 разных разреза на один файл
        chosen_strategies = random.choices(strategies, weights=weights, k=4)

        generated_fims = []

        used_caret_positions = set()

        for strategy in chosen_strategies:
            caret_pos = None

            if strategy == 'syntax' and syntax_markers:
                caret_pos = random.choice(syntax_markers)
            elif strategy == 'healing' and mid_word_borders:
                caret_pos = random.choice(mid_word_borders)
            elif strategy == 'qwen' and qwen_borders:
                caret_pos = random.choice(qwen_borders)
            elif strategy == 'lexical' and lexical_borders:
                caret_pos = random.choice(lexical_borders)

            if caret_pos is None or caret_pos >= len(code) or caret_pos in used_caret_positions:
                continue

            # Разрезаем текст по каретке
            prefix_all = code[:caret_pos]
            remaining = code[caret_pos:]

            middle_line = remaining.split('\n')[0] # Берём строго первую строку после каретки
            if not middle_line.strip():
                # print('Сэмлп не подходит!!!')
                continue

            suffix_all = remaining[len(middle_line):] if not is_empty_suffix else ""

            # -----------------------------------------------------------------
            # 🛡️ УМНАЯ СИНТАКСИЧЕСКАЯ ФИЛЬТРАЦИЯ СЭМПЛА
            # -----------------------------------------------------------------
            # Очищаем сэмпл от пробелов, переносов строк и базовых ключевых слов начала блока
            # Чтобы понять, есть ли в префиксе реальный написанный код
            clean_content = (prefix_all + "\n" + suffix_all).strip()

            # Удаляем из оценки все пустые "каркасные" токены Паскаля (без учета регистра)
            # Убираем ##, var, begin, program, а также точки, запятые и точки с запятой
            clean_content = re.sub(r'(##|var|begin|end|program|const|uses|[;.,\s\n\r])', '', clean_content, flags=re.IGNORECASE)

            # Условие: Если после удаления каркасных слов в префиксе осталось меньше 4 символов,
            # значит пользователь стоит внутри пустого begin-end, пустой секции var или в начале файла.
            # Модели здесь не на что опираться, поэтому сэмпл выбрасываем.
            if len(clean_content) < 4:
                # print('Бесполезный сэмпл!!!!')
                continue
            # -----------------------------------------------------------------

            # --- УМНАЯ ОБРЕЗКА ПОД МАКСИМАЛЬНЫЙ ЛИМИТ (например, 512 или 1024) ---
            # Переводим в токены сырые куски, чтобы точно знать их длину
            pref_ids = self.tokenizer.encode(prefix_all)
            suff_ids = self.tokenizer.encode(suffix_all)
            mid_ids = self.tokenizer.encode(middle_line)

            # Оставляем запас под спецтокены FIM и сам ответ
            max_context_budget = self.cfg.max_seq_length - len(mid_ids) - 10

            # Если мы не влезаем в лимит, пропорционально урезаем контекст вокруг каретки
            if len(pref_ids) + len(suff_ids) > max_context_budget:
                # Префикс оставляем С КОНЦА (код непосредственно ВЫШЕ курсора)
                prefix_all = self.tokenizer.decode(pref_ids[-int(max_context_budget * self.cfg.prefix_percent_when_cutting):])
                # Суффикс оставляем С НАЧАЛА (код непосредственно НИЖЕ курсора)
                if suffix_all:
                    suffix_all = self.tokenizer.decode(suff_ids[:int(max_context_budget * self.cfg.suffix_percent_when_cutting)])

            # Теперь собираем финальный FIM-текст — он гарантированно не превысит max_length
            fim_text = self.create_fim_structure(prefix_all, suffix_all, middle_line)
            used_caret_positions.add(caret_pos)
            generated_fims.append(fim_text)


        return generated_fims

