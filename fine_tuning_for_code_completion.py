from transformers import TrainerCallback, TrainerControl, TrainingArguments, TrainerState

class CodeCompletionEvalCallback(TrainerCallback):
    """Callback, который на каждой эпохе считает процент идеальных строк (Perfect Lines)."""
    def __init__(self, eval_dataset, tokenizer, num_samples=50):
        self.eval_dataset = eval_dataset
        self.tokenizer = tokenizer
        self.num_samples = min(num_samples, len(eval_dataset))

    def on_evaluate(self, args: TrainingArguments, state: TrainerState, control: TrainerControl, **kwargs):
        model = kwargs['model']
        model.eval()
        perfect_lines_count = 0

        print(f"\nЗапуск генеративной валидации (Perfect Lines) на {self.num_samples} сэмплах...")

        # Извлекаем токены FIM для парсинга
        prefix_tok = "<|fim_prefix|>"
        suffix_tok = "<|fim_suffix|>"
        middle_tok = "<|fim_middle|>"

        for i in range(self.num_samples):
            full_text = self.eval_dataset[i]['text']

            # Находим индексы спецтокенов в сыром тексте
            try:
                p_start = full_text.find(prefix_tok) + len(prefix_tok)
                p_end = full_text.find(suffix_tok)
                s_start = p_end + len(suffix_tok)
                s_end = full_text.find(middle_tok)
                m_start = s_end + len(middle_tok)

                prefix = full_text[p_start:p_end]
                suffix = full_text[s_start:s_end]
                expected_middle = full_text[m_start:].replace(self.tokenizer.eos_token, "").strip()
            except Exception:
                continue

            # Формируем prompt для генерации (модель должна дописать то, что после <fim_middle>)
            prompt = f"{prefix_tok}{prefix}{suffix_tok}{suffix}{middle_tok}"
            inputs = self.tokenizer(prompt, return_tensors="pt").to(model.device)
            with torch.no_grad():
              outputs = model.generate(
                **inputs,
                max_new_tokens=32, # ограничение по генерации !!!
                pad_token_id=self.tokenizer.eos_token_id,
                eos_token_id=self.tokenizer.eos_token_id
            )
            # Декодируем только сгенерированную часть
            generated_text = self.tokenizer.decode(outputs[0][inputs.input_ids.shape[1]:])
            generated_middle = generated_text.replace(self.tokenizer.eos_token, "").strip()
            # Проверяем на идеальное совпадение
            if generated_middle == expected_middle:
              perfect_lines_count += 1

        perfect_lines_ratio = perfect_lines_count / self.num_samples
        print(f">> Эпоха {state.epoch}: Метрика Perfect Lines = {perfect_lines_ratio * 100:.2f}%")

        model.train()

