# 2. ПРОСТЕЙШИЙ ЛЕКСЕР ДЛЯ PASCAL (ДЛЯ ГРУППЫ Г)
# =====================================================================
def get_pascal_lexical_borders(text: str) -> List[int]:
    """Находит индексы символов, которые являются концами токенов Pascal."""
    # Регулярка для поиска слов, чисел и операторов PascalABC.NET
    pattern = r'[a-zA-Z_][a-zA-Z0-9_]*|[0-9]+|:=|<=|>=|<>|[-+*/=<>:;.,()\[\]]'
    borders = []
    for match in re.finditer(pattern, text):
        borders.append(match.end()) # Индекс СРАЗУ ПОСЛЕ завершенного токена языка
    return borders

